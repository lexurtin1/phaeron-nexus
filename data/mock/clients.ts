import type { Client, SparkPoint } from "@/data/types";

function spark(base: number, variance: number): SparkPoint[] {
  return Array.from({ length: 24 }, (_, i) => {
    const noise = (Math.sin(i * 0.7 + base) + Math.cos(i * 0.3)) * variance;
    return { t: `${i}h`, v: Math.max(0, Number((base + noise).toFixed(2))) };
  });
}

function deployment(
  overrides: Partial<Client["deployment"]> & {
    uptime: number;
    latencyP99: number;
    errorRate: number;
    evaluationScore: number;
  }
): Client["deployment"] {
  return {
    runtimeStatus: overrides.runtimeStatus ?? "healthy",
    kubernetesHealth: overrides.kubernetesHealth ?? "healthy",
    apiGateway: overrides.apiGateway ?? "healthy",
    lastCall: overrides.lastCall ?? "2026-09-16T12:58:00Z",
    uptime: overrides.uptime,
    latencyP99: overrides.latencyP99,
    errorRate: overrides.errorRate,
    evaluationScore: overrides.evaluationScore,
    sparklines: {
      uptime: spark(overrides.uptime, 0.4),
      latency: spark(overrides.latencyP99, overrides.latencyP99 * 0.08),
      errors: spark(overrides.errorRate, overrides.errorRate * 0.3 || 0.02),
      evaluation: spark(overrides.evaluationScore, 1.2),
    },
  };
}

